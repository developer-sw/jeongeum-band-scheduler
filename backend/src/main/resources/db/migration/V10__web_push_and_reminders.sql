-- Add delivery and reminder plans without backfilling historical inbox/reservation rows.
ALTER TABLE notifications DROP CONSTRAINT notifications_event_type_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_event_type_check CHECK (event_type IN (
    'IMPORTANT_NOTICE','RESERVATION_CREATED','RESERVATION_CHANGED','RESERVATION_CANCELED',
    'EXCHANGE_REQUESTED','EXCHANGE_COMPLETED','EXCHANGE_REJECTED','EXCHANGE_WITHDRAWN','EXCHANGE_EXPIRED',
    'EXCHANGE_INVALIDATED','START_REMINDER'));

CREATE TABLE push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    endpoint VARCHAR(2048) NOT NULL UNIQUE CHECK (endpoint LIKE 'https://%'),
    p256dh VARCHAR(120) NOT NULL,
    auth VARCHAR(40) NOT NULL,
    device_name VARCHAR(80) NOT NULL CHECK (length(btrim(device_name)) BETWEEN 1 AND 80),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    session_digest CHAR(64) NOT NULL,
    binding_version BIGINT NOT NULL DEFAULT 0 CHECK (binding_version >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deactivated_at TIMESTAMPTZ,
    CHECK (active = (deactivated_at IS NULL))
);
CREATE INDEX push_subscriptions_owner_idx ON push_subscriptions(user_id,active,id);
CREATE INDEX push_subscriptions_session_idx ON push_subscriptions(user_id,session_digest) WHERE active;

CREATE TABLE notification_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_kind VARCHAR(24) NOT NULL CHECK (job_kind IN ('REMINDER_PLAN','PUSH_DELIVERY')),
    job_key VARCHAR(240) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','RETRY_WAIT','COMPLETED','SENT','FAILED','CANCELED')),
    reservation_id BIGINT REFERENCES reservations(id),
    expected_version BIGINT CHECK (expected_version >= 0),
    logical_root_ids BIGINT[],
    owner_type VARCHAR(10) CHECK (owner_type IN ('PERSONAL','TEAM')),
    owner_user_id BIGINT REFERENCES users(id),
    team_id BIGINT REFERENCES teams(id),
    actual_start_at TIMESTAMPTZ,
    notification_id BIGINT REFERENCES notifications(id),
    subscription_id BIGINT REFERENCES push_subscriptions(id),
    subscription_binding_version BIGINT CHECK (subscription_binding_version >= 0),
    scheduled_at TIMESTAMPTZ NOT NULL,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    lease_token UUID,
    lease_expires_at TIMESTAMPTZ,
    last_error_code VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    canceled_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    CHECK ((job_kind='REMINDER_PLAN' AND reservation_id IS NOT NULL AND expected_version IS NOT NULL
            AND logical_root_ids IS NOT NULL AND cardinality(logical_root_ids)>0 AND owner_type IS NOT NULL
            AND actual_start_at IS NOT NULL AND notification_id IS NULL AND subscription_id IS NULL)
        OR (job_kind='PUSH_DELIVERY' AND notification_id IS NOT NULL AND subscription_id IS NOT NULL
            AND subscription_binding_version IS NOT NULL)),
    CHECK ((lease_token IS NULL) = (lease_expires_at IS NULL)),
    CHECK (job_kind <> 'REMINDER_PLAN' OR ((owner_type='PERSONAL' AND owner_user_id IS NOT NULL AND team_id IS NULL)
        OR (owner_type='TEAM' AND owner_user_id IS NULL AND team_id IS NOT NULL))),
    CHECK ((job_kind='REMINDER_PLAN' AND status<>'SENT') OR (job_kind='PUSH_DELIVERY' AND status<>'COMPLETED')),
    CHECK (status <> 'PROCESSING' OR lease_token IS NOT NULL),
    CHECK (status <> 'SENT' OR sent_at IS NOT NULL)
);
CREATE INDEX notification_jobs_due_idx ON notification_jobs(job_kind,next_attempt_at,id) WHERE status IN ('PENDING','RETRY_WAIT','PROCESSING');
CREATE INDEX notification_jobs_reservation_idx ON notification_jobs(reservation_id,job_kind,status);
CREATE INDEX notification_jobs_subscription_idx ON notification_jobs(subscription_id,status);
