CREATE TABLE announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(120) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
    body TEXT NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 10000),
    pinned BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE INDEX announcements_visible_order_idx ON announcements(pinned DESC, created_at DESC, id DESC) WHERE deleted_at IS NULL;

CREATE TABLE notice_idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    key_digest CHAR(64) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    http_method VARCHAR(10) NOT NULL CHECK (http_method IN ('POST','PATCH','DELETE')),
    route VARCHAR(120) NOT NULL,
    response_status INTEGER NOT NULL CHECK (response_status IN (200,201)),
    result_notice_id BIGINT NOT NULL REFERENCES announcements(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (actor_user_id,key_digest)
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    event_key VARCHAR(160) NOT NULL,
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN ('IMPORTANT_NOTICE','RESERVATION_CREATED','RESERVATION_CHANGED','RESERVATION_CANCELED',
        'EXCHANGE_REQUESTED','EXCHANGE_COMPLETED','EXCHANGE_REJECTED','EXCHANGE_WITHDRAWN','EXCHANGE_EXPIRED','EXCHANGE_INVALIDATED')),
    operation_id BIGINT REFERENCES reservation_operations(id),
    reservation_id BIGINT REFERENCES reservations(id),
    exchange_request_id BIGINT REFERENCES exchange_requests(id),
    announcement_id BIGINT REFERENCES announcements(id),
    title VARCHAR(120) NOT NULL,
    body VARCHAR(2000) NOT NULL,
    target_path VARCHAR(240) NOT NULL CHECK (target_path LIKE '/%' AND target_path NOT LIKE '//%'),
    created_at TIMESTAMPTZ NOT NULL,
    read_at TIMESTAMPTZ,
    UNIQUE (event_key,user_id),
    CHECK (read_at IS NULL OR read_at >= created_at)
);
CREATE INDEX notifications_owner_page_idx ON notifications(user_id,id DESC);
CREATE INDEX notifications_owner_unread_idx ON notifications(user_id,id DESC) WHERE read_at IS NULL;
