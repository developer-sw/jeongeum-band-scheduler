CREATE TABLE exchange_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','COMPLETED','REJECTED','CANCELED','EXPIRED','INVALIDATED')),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    processed_at TIMESTAMPTZ,
    processed_by_user_id BIGINT REFERENCES users(id),
    state_reason VARCHAR(40),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK (expires_at > created_at),
    CHECK ((status = 'PENDING') = (processed_at IS NULL)),
    CHECK (status NOT IN ('COMPLETED','REJECTED','CANCELED') OR processed_by_user_id IS NOT NULL)
);
CREATE INDEX exchange_requests_pending_idx ON exchange_requests(expires_at, id) WHERE status = 'PENDING';
CREATE INDEX exchange_requests_requester_idx ON exchange_requests(requester_user_id, id);
CREATE TABLE exchange_request_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange_request_id BIGINT NOT NULL REFERENCES exchange_requests(id),
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    expected_reservation_version BIGINT NOT NULL CHECK (expected_reservation_version >= 0),
    side VARCHAR(20) NOT NULL CHECK (side IN ('REQUESTER','COUNTERPART')),
    sequence_no INTEGER NOT NULL CHECK (sequence_no IN (0,1)),
    UNIQUE (exchange_request_id, reservation_id),
    UNIQUE (exchange_request_id, side, sequence_no)
);
CREATE INDEX exchange_request_items_reservation_idx ON exchange_request_items(reservation_id,exchange_request_id);
CREATE TABLE exchange_instrument_allocations (
    exchange_request_id BIGINT NOT NULL,
    reservation_id BIGINT NOT NULL,
    target_sequence_no INTEGER NOT NULL CHECK (target_sequence_no IN (0,1)),
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    PRIMARY KEY (exchange_request_id,reservation_id,target_sequence_no),
    UNIQUE (exchange_request_id,reservation_id,asset_id),
    FOREIGN KEY (exchange_request_id,reservation_id) REFERENCES exchange_request_items(exchange_request_id,reservation_id)
);
ALTER TABLE reservation_operations ADD COLUMN exchange_request_id BIGINT REFERENCES exchange_requests(id);
CREATE UNIQUE INDEX reservation_operations_exchange_unique ON reservation_operations(exchange_request_id) WHERE exchange_request_id IS NOT NULL;
CREATE TABLE exchange_idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    key_digest CHAR(64) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    http_method VARCHAR(10) NOT NULL CHECK (http_method IN ('POST','PATCH')),
    route VARCHAR(120) NOT NULL,
    response_status INTEGER NOT NULL CHECK (response_status IN (200,201)),
    result_exchange_request_id BIGINT NOT NULL REFERENCES exchange_requests(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (actor_user_id,key_digest)
);
