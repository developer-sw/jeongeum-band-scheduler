CREATE TABLE recurring_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ENDED')),
    end_date DATE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    UNIQUE (id, team_id),
    CHECK ((status = 'ENDED') = (end_date IS NOT NULL))
);
CREATE TABLE recurring_assignment_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES recurring_assignments(id),
    revision_no BIGINT NOT NULL CHECK (revision_no >= 1),
    effective_date DATE NOT NULL,
    weekday INTEGER NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    time_block_code VARCHAR(3) NOT NULL REFERENCES time_blocks(code),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (assignment_id, revision_no),
    UNIQUE (id, assignment_id)
);
CREATE TABLE recurring_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES recurring_assignments(id),
    week_start_date DATE NOT NULL CHECK (EXTRACT(ISODOW FROM week_start_date) = 1),
    pattern_revision_id BIGINT NOT NULL,
    original_scheduled_date DATE NOT NULL,
    original_block_code VARCHAR(3) NOT NULL REFERENCES time_blocks(code),
    state VARCHAR(30) NOT NULL CHECK (state IN ('PLANNED','MATERIALIZED','CANCELED_EXCEPTION','CHANGED_EXCEPTION','EXCHANGED_EXCEPTION','ENDED')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    UNIQUE (assignment_id, week_start_date),
    UNIQUE (id, assignment_id),
    FOREIGN KEY (pattern_revision_id, assignment_id) REFERENCES recurring_assignment_revisions(id, assignment_id),
    CHECK (original_scheduled_date BETWEEN week_start_date AND week_start_date + 6)
);
CREATE TABLE recurring_occurrence_reservations (
    occurrence_id BIGINT NOT NULL REFERENCES recurring_occurrences(id),
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    link_role VARCHAR(20) NOT NULL CHECK (link_role IN ('ORIGINAL','SUCCESSOR')),
    is_current BOOLEAN NOT NULL,
    PRIMARY KEY (occurrence_id, reservation_id)
);
CREATE TABLE recurring_idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    key_digest CHAR(64) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    http_method VARCHAR(10) NOT NULL CHECK (http_method IN ('POST','PATCH')),
    route VARCHAR(120) NOT NULL,
    response_status INTEGER NOT NULL CHECK (response_status IN (200,201)),
    result_assignment_id BIGINT NOT NULL REFERENCES recurring_assignments(id),
    operation_id BIGINT NOT NULL REFERENCES reservation_operations(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (actor_user_id, key_digest)
);
CREATE INDEX recurring_occurrences_date_idx ON recurring_occurrences(original_scheduled_date, assignment_id);
CREATE INDEX recurring_occurrence_reservation_idx ON recurring_occurrence_reservations(reservation_id) WHERE is_current;

