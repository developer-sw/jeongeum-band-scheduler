CREATE TABLE asset_incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED')),
    description VARCHAR(1000) NOT NULL CHECK (length(trim(description)) BETWEEN 1 AND 1000),
    origin VARCHAR(20) NOT NULL CHECK (origin IN ('ADMIN','LEGACY')),
    reported_by_user_id BIGINT REFERENCES users(id),
    reported_at TIMESTAMPTZ NOT NULL,
    resolved_by_user_id BIGINT REFERENCES users(id),
    resolved_at TIMESTAMPTZ,
    resolution_note VARCHAR(1000),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK ((origin = 'ADMIN') = (reported_by_user_id IS NOT NULL)),
    CHECK ((status = 'OPEN') = (resolved_at IS NULL)),
    CHECK ((status = 'RESOLVED') = (resolved_by_user_id IS NOT NULL)),
    CHECK (status = 'RESOLVED' OR resolution_note IS NULL),
    CHECK (resolved_at IS NULL OR resolved_at >= reported_at)
);
CREATE UNIQUE INDEX asset_incidents_open_asset_unique ON asset_incidents(asset_id) WHERE status = 'OPEN';
CREATE INDEX asset_incidents_asset_history_idx ON asset_incidents(asset_id, id DESC);

