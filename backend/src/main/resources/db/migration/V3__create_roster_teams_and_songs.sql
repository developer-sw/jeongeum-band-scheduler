ALTER TABLE invitation_codes ADD COLUMN roster_entry_id BIGINT REFERENCES roster_entries(id);
CREATE UNIQUE INDEX invitation_one_pending_per_roster ON invitation_codes (roster_entry_id)
    WHERE roster_entry_id IS NOT NULL AND used_at IS NULL AND revoked_at IS NULL;

CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL CHECK (length(btrim(name)) > 0),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('REGULAR', 'ADDITIONAL')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISBANDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);

CREATE TABLE team_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id),
    roster_entry_id BIGINT NOT NULL REFERENCES roster_entries(id),
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER' CHECK (role IN ('MEMBER', 'LEADER')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'REMOVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE UNIQUE INDEX team_one_active_membership ON team_memberships (team_id, roster_entry_id)
    WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX team_one_active_leader ON team_memberships (team_id)
    WHERE status = 'ACTIVE' AND role = 'LEADER';
CREATE INDEX team_memberships_roster_idx ON team_memberships (roster_entry_id, team_id)
    WHERE status = 'ACTIVE';

CREATE TABLE team_songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id),
    title VARCHAR(120) NOT NULL CHECK (length(btrim(title)) > 0),
    artist VARCHAR(120),
    memo VARCHAR(1000),
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE INDEX team_songs_order_idx ON team_songs (team_id, sort_order, id);

CREATE TABLE member_role_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id BIGINT NOT NULL REFERENCES users(id),
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    old_role VARCHAR(20) NOT NULL CHECK (old_role IN ('MEMBER', 'GLOBAL_ADMIN')),
    new_role VARCHAR(20) NOT NULL CHECK (new_role IN ('MEMBER', 'GLOBAL_ADMIN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
