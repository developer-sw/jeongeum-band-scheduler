CREATE TABLE booking_days (
    reservation_date DATE PRIMARY KEY,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PREPARING','OPEN')),
    opened_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK ((status = 'OPEN') = (opened_at IS NOT NULL))
);

CREATE TABLE reservation_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(30) NOT NULL CHECK (kind IN ('CREATE','CANCEL','CHANGE','EXCHANGE','FIXED_GENERATE','SERIES_UPDATE','USER_WITHDRAW','TEAM_DISBAND')),
    actor_kind VARCHAR(10) NOT NULL CHECK (actor_kind IN ('USER','SYSTEM')),
    actor_user_id BIGINT REFERENCES users(id),
    occurred_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(500),
    CHECK ((actor_kind = 'USER') = (actor_user_id IS NOT NULL))
);

