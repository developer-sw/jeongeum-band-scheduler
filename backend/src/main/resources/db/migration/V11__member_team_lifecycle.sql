-- Keep identities, bookings, songs and completed history; closures are auditable soft transitions.
ALTER TABLE teams ADD COLUMN disbanded_at TIMESTAMPTZ;

CREATE TABLE lifecycle_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    key_digest CHAR(64) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('USER_WITHDRAW', 'TEAM_DISBAND')),
    target_user_id BIGINT REFERENCES users(id),
    target_team_id BIGINT REFERENCES teams(id),
    expected_version BIGINT NOT NULL CHECK (expected_version >= 0),
    result_status VARCHAR(20) NOT NULL CHECK (result_status IN ('WITHDRAWN', 'DISBANDED')),
    result_version BIGINT NOT NULL CHECK (result_version >= 0),
    reservation_operation_id BIGINT NOT NULL REFERENCES reservation_operations(id),
    canceled_reservations INTEGER NOT NULL CHECK (canceled_reservations >= 0),
    invalidated_exchanges INTEGER NOT NULL CHECK (invalidated_exchanges >= 0),
    ended_assignments INTEGER NOT NULL CHECK (ended_assignments >= 0),
    deactivated_subscriptions INTEGER NOT NULL CHECK (deactivated_subscriptions >= 0),
    revoked_sessions INTEGER NOT NULL CHECK (revoked_sessions >= 0),
    reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (actor_user_id, key_digest),
    CHECK ((kind = 'USER_WITHDRAW' AND target_user_id IS NOT NULL AND target_team_id IS NULL
            AND result_status = 'WITHDRAWN')
        OR (kind = 'TEAM_DISBAND' AND target_team_id IS NOT NULL AND target_user_id IS NULL
            AND result_status = 'DISBANDED'))
);
CREATE INDEX lifecycle_operations_user_history ON lifecycle_operations(target_user_id, id DESC)
    WHERE target_user_id IS NOT NULL;
CREATE INDEX lifecycle_operations_team_history ON lifecycle_operations(target_team_id, id DESC)
    WHERE target_team_id IS NOT NULL;
CREATE INDEX reservations_remaining_personal ON reservations(owner_user_id, block_end_at, id)
    WHERE status = 'CONFIRMED' AND owner_type = 'PERSONAL';
CREATE INDEX reservations_remaining_team ON reservations(team_id, block_end_at, id)
    WHERE status = 'CONFIRMED' AND owner_type = 'TEAM';
