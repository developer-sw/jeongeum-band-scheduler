-- Preserve replacement history independently of reservation dates and recurring week keys.
CREATE TABLE reservation_lineage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id BIGINT NOT NULL REFERENCES reservation_operations(id),
    source_reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    successor_reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (operation_id, source_reservation_id, successor_reservation_id),
    CHECK (source_reservation_id <> successor_reservation_id)
);
CREATE INDEX reservation_lineage_source_idx ON reservation_lineage(source_reservation_id, successor_reservation_id);
CREATE INDEX reservation_lineage_successor_idx ON reservation_lineage(successor_reservation_id, source_reservation_id);
