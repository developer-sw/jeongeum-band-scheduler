/** Actual @Scheduled/startup execution in separate fresh JVMs, with no provider or development DB access. */
@Testcontainers
@ActiveProfiles("local")
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT,
        properties = {"jeongeum.recurring.worker.enabled=false", "jeongeum.exchange.worker.enabled=false",
                "jeongeum.push.worker.enabled=false", "jeongeum.reminder.worker.enabled=false"})
@Import(PushWorkerRuntimeIntegrationTest.FixtureTime.class)
@Timeout(180)
class PushWorkerRuntimeIntegrationTest {
    private static final Instant INITIAL = Instant.parse("2026-10-30T02:00:00Z");
    private static final Instant REMINDER_DUE = Instant.parse("2026-10-30T08:00:00Z");
    private static final LocalDate DAY = LocalDate.of(2026, 10, 30);
    @Container static final PostgreSQLContainer POSTGRES = new PostgreSQLContainer(
            "postgres@sha256:3645570cccdfa447589da9f57dd740faa29b30938e861289a5574b6ca6b03826")
            .withDatabaseName("push_worker_runtime_test").withUsername("push_worker_runtime_test")
            .withPassword(UUID.randomUUID().toString()).withStartupTimeout(Duration.ofMinutes(2));

    @DynamicPropertySource static void database(DynamicPropertyRegistry registry) {
        registry.add("APP_DB_URL", POSTGRES::getJdbcUrl);
        registry.add("APP_DB_USERNAME", POSTGRES::getUsername);
        registry.add("APP_DB_PASSWORD", POSTGRES::getPassword);
    }

    @Autowired JdbcTemplate jdbc;
    @Autowired MemberRepository members;
    @Autowired ReservationService reservations;
    @Autowired RecurringOpeningService opening;
    private long owner;

    @BeforeEach void setup() {
        assertEquals("push_worker_runtime_test", POSTGRES.getDatabaseName());
        jdbc.execute("TRUNCATE booking_days,teams,roster_entries,invitation_codes,users,spring_session RESTART IDENTITY CASCADE");
        jdbc.execute("CREATE TABLE IF NOT EXISTS runtime_worker_clock(id INT PRIMARY KEY,controlled_at TIMESTAMPTZ NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS runtime_worker_calls(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,job_id BIGINT NOT NULL,notification_id BIGINT NOT NULL,pid BIGINT NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS runtime_worker_registration(pid BIGINT PRIMARY KEY,reminder_tasks INT NOT NULL,delivery_tasks INT NOT NULL,ready BOOLEAN NOT NULL)");
        jdbc.execute("TRUNCATE runtime_worker_clock,runtime_worker_calls,runtime_worker_registration RESTART IDENTITY");
        jdbc.update("INSERT INTO runtime_worker_clock VALUES (1,?)", Timestamp.from(INITIAL));
        owner = members.insert("worker-" + UUID.randomUUID().toString().substring(0, 16), "synthetic-unused-password-hash",
                "합성 스케줄 검증 회원", "MEMBER", INITIAL).orElseThrow().id();
        // API validation and encryption have separate tests; this endpoint can only reach the in-memory fake sender.
        jdbc.update("""
                INSERT INTO push_subscriptions(user_id,endpoint,p256dh,auth,device_name,session_digest,created_at,updated_at)
                VALUES (?,?,'synthetic-test-public-key','synthetic-test-auth','격리 worker 테스트',?,?,?)
                """, owner, "https://fcm.googleapis.com/fcm/send/runtime-test-" + UUID.randomUUID(),
                "0".repeat(64), Timestamp.from(INITIAL), Timestamp.from(INITIAL));
        opening.prepareRange(DAY, DAY.plusDays(14));
    }

    @Test void actualSchedulersRecoverThenDeliverOneReminderAcrossTwoJvmsAndRestart() throws Exception {
        ReservationResponse reservation = personal();
        assertEquals(1, count("notifications"));
        assertEquals(1, jobs("REMINDER_PLAN", "PENDING"));
        // Simulate a committed booking whose future plan is missing before rollout/restart.
        jdbc.update("DELETE FROM notification_jobs WHERE job_kind='REMINDER_PLAN'");
        Process first = startJvm();
        Process second = null;
        Process restarted = null;
        try {
            awaitReady(first);
            second = startJvm();
            awaitReady(second);
            await(() -> jobs("PUSH_DELIVERY", "SENT") == 1);
            assertEquals(1, jobs("REMINDER_PLAN", "PENDING"));
            assertEquals(1, count("notifications"), "Startup recovers the plan without another CREATED inbox event");
            assertEquals(0, reminders());
            assertRegisteredSchedulers(2);
            setTime(REMINDER_DUE);
            // Both JVMs have completed their startup callbacks. Only the actual scheduled polls can process this due time.
            await(() -> reminders() == 1 && jobs("PUSH_DELIVERY", "SENT") == 2);
            assertEquals(1, jobs("REMINDER_PLAN", "COMPLETED"));
            assertEquals(2, count("runtime_worker_calls"));
            assertEquals(2, jdbc.queryForObject("SELECT count(DISTINCT job_id) FROM runtime_worker_calls", Integer.class));
            assertEquals(Long.parseLong(reservation.id()), jdbc.queryForObject(
                    "SELECT reservation_id FROM notifications WHERE event_type='START_REMINDER'", Long.class));
            stopJvm(first);
            stopJvm(second);
            List<Map<String,Object>> inboxBefore = jdbc.queryForList("SELECT * FROM notifications ORDER BY id");
            List<Map<String,Object>> jobsBefore = jdbc.queryForList("SELECT id,job_kind,job_key,status,attempts FROM notification_jobs ORDER BY id");
            restarted = startJvm();
            awaitReady(restarted);
            assertRegisteredSchedulers(3);
            org.awaitility.Awaitility.await().during(Duration.ofSeconds(2)).atMost(Duration.ofSeconds(10)).until(() ->
                    count("runtime_worker_calls") == 2 && reminders() == 1);
            assertEquals(inboxBefore, jdbc.queryForList("SELECT * FROM notifications ORDER BY id"));
            assertEquals(jobsBefore, jdbc.queryForList("SELECT id,job_kind,job_key,status,attempts FROM notification_jobs ORDER BY id"));
        } finally {
            stopJvm(first); stopJvm(second); stopJvm(restarted);
        }
    }

    @Test void restartKeepsCanceledReservationPlanTerminalAndNeverSendsItsReminder() throws Exception {
        ReservationResponse reservation = personal();
        reservations.cancel(owner, Long.parseLong(reservation.id()), UUID.randomUUID().toString(),
                new ReservationRequests.Cancel(reservation.version(), null));
        assertEquals(1, jobs("REMINDER_PLAN", "CANCELED"));
        setTime(REMINDER_DUE);
        Process process = startJvm();
        try {
            awaitReady(process);
            await(() -> jobs("PUSH_DELIVERY", "SENT") == 1 && jobs("PUSH_DELIVERY", "CANCELED") == 1);
            assertRegisteredSchedulers(1);
            assertEquals(0, reminders());
            assertEquals(1, jobs("REMINDER_PLAN", "CANCELED"));
            assertEquals(1, count("runtime_worker_calls"));
            assertEquals("RESERVATION_CANCELED", jdbc.queryForObject("""
                    SELECT n.event_type FROM runtime_worker_calls c JOIN notifications n ON n.id=c.notification_id
                    """, String.class));
        } finally { stopJvm(process); }
    }

    private ReservationResponse personal() {
        return reservations.create(owner, UUID.randomUUID().toString(),
                new ReservationRequests.Create("PERSONAL", null, DAY.toString(), "B07", List.of("DRUMS"))).reservation();
    }
    private int count(String table) { return jdbc.queryForObject("SELECT count(*) FROM " + table, Integer.class); }
    private int jobs(String kind, String status) {
        return jdbc.queryForObject("SELECT count(*) FROM notification_jobs WHERE job_kind=? AND status=?", Integer.class, kind, status);
    }
    private int reminders() {
        return jdbc.queryForObject("SELECT count(*) FROM notifications WHERE event_type='START_REMINDER'", Integer.class);
    }
    private void setTime(Instant time) { jdbc.update("UPDATE runtime_worker_clock SET controlled_at=? WHERE id=1", Timestamp.from(time)); }
    private void await(java.util.concurrent.Callable<Boolean> condition) {
        org.awaitility.Awaitility.await().atMost(Duration.ofSeconds(35)).pollInterval(Duration.ofMillis(100)).until(condition);
    }
    private void awaitReady(Process process) {
        org.awaitility.Awaitility.await().atMost(Duration.ofSeconds(45)).pollInterval(Duration.ofMillis(200)).until(() -> {
            assertTrue(process.isAlive(), "Isolated no-network worker JVM exited during startup");
            return jdbc.queryForObject("SELECT EXISTS(SELECT 1 FROM runtime_worker_registration WHERE pid=? AND ready)",
                    Boolean.class, process.pid());
        });
    }
    private void assertRegisteredSchedulers(int processes) {
        assertEquals(processes, count("runtime_worker_registration"));
        assertEquals(processes, jdbc.queryForObject("""
                SELECT count(*) FROM runtime_worker_registration WHERE reminder_tasks=1 AND delivery_tasks=1 AND ready
                """, Integer.class));
    }

    private Process startJvm() throws Exception {
        assertEquals("push_worker_runtime_test", POSTGRES.getDatabaseName());
        Path javaBinary = Path.of(System.getProperty("java.home"), "bin", System.getProperty("os.name")
                .toLowerCase().contains("windows") ? "java.exe" : "java");
        int port;
        try (ServerSocket socket = new ServerSocket(0, 1, InetAddress.getByName("127.0.0.1"))) { port = socket.getLocalPort(); }
        ProcessBuilder builder = new ProcessBuilder(javaBinary.toString(), "-Xmx192m",
                "-Dloader.path=build/classes/java/test", "-Dloader.main=kr.jeongeum.scheduler.pushruntime.PushWorkerTestApplication",
                "-cp", "build/libs/jeongeum-band-scheduler-backend-0.0.1-SNAPSHOT.jar",
                "org.springframework.boot.loader.launch.PropertiesLauncher", "--server.port=" + port,
                "--jeongeum.recurring.worker.enabled=false", "--jeongeum.exchange.worker.enabled=false",
                "--jeongeum.push.enabled=false", "--jeongeum.push.worker.enabled=true", "--jeongeum.push.worker.delay-ms=250",
                "--jeongeum.reminder.worker.enabled=true", "--jeongeum.reminder.worker.delay-ms=250");
        builder.environment().put("APP_DB_URL", POSTGRES.getJdbcUrl());
        builder.environment().put("APP_DB_USERNAME", POSTGRES.getUsername());
        builder.environment().put("APP_DB_PASSWORD", POSTGRES.getPassword());
        builder.redirectErrorStream(true);
        Path log = Path.of("build", "tmp", "push-worker-runtime", UUID.randomUUID() + ".log");
        java.nio.file.Files.createDirectories(log.getParent());
        builder.redirectOutput(log.toFile());
        Process process = builder.start();
        return process;
    }
    private void stopJvm(Process process) throws Exception {
        if (process == null || !process.isAlive()) return;
        process.destroy();
        if (!process.waitFor(10, TimeUnit.SECONDS)) {
            process.destroyForcibly();
            assertTrue(process.waitFor(10, TimeUnit.SECONDS), "Isolated worker JVM did not stop");
        }
    }

    @TestConfiguration(proxyBeanMethods = false) static class FixtureTime {
        @Bean @Primary Clock runtimeFixtureClock() { return Clock.fixed(INITIAL, ZoneOffset.UTC); }
    }
}
