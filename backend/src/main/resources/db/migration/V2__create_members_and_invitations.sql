CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(32) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(40) NOT NULL,
    global_role VARCHAR(20) NOT NULL CHECK (global_role IN ('MEMBER', 'GLOBAL_ADMIN')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE', 'WITHDRAWN')),
    created_at TIMESTAMPTZ NOT NULL,
    withdrawn_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT users_login_id_normalized CHECK (login_id = lower(login_id)
        AND login_id ~ '^[a-z0-9][a-z0-9._-]{2,31}$')
);

CREATE TABLE invitation_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_digest CHAR(64) NOT NULL UNIQUE,
    recipient_name VARCHAR(40) NOT NULL,
    issued_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    used_by BIGINT REFERENCES users(id),
    revoked_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT invitation_expiry_after_creation CHECK (expires_at > created_at),
    CONSTRAINT invitation_use_consistent CHECK ((used_at IS NULL) = (used_by IS NULL)),
    CONSTRAINT invitation_terminal_state CHECK (used_at IS NULL OR revoked_at IS NULL)
);

CREATE INDEX invitation_codes_created_idx ON invitation_codes (id DESC);

