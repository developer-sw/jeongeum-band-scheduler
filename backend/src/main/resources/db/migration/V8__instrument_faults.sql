CREATE TABLE instrument_fault_idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    key_digest CHAR(64) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    http_method VARCHAR(10) NOT NULL CHECK (http_method = 'POST'),
    route VARCHAR(120) NOT NULL,
    response_status INTEGER NOT NULL CHECK (response_status IN (200,201)),
    result_incident_id BIGINT NOT NULL REFERENCES asset_incidents(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (actor_user_id,key_digest)
);
