CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type VARCHAR(20) NOT NULL CHECK (owner_type IN ('PERSONAL','TEAM')),
    purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('PERSONAL','REGULAR','ADDITIONAL')),
    owner_user_id BIGINT REFERENCES users(id),
    team_id BIGINT REFERENCES teams(id),
    creator_user_id BIGINT NOT NULL REFERENCES users(id),
    reservation_date DATE NOT NULL REFERENCES booking_days(reservation_date),
    time_block_code VARCHAR(3) NOT NULL,
    block_start_minute INTEGER NOT NULL,
    block_end_minute INTEGER NOT NULL,
    duration_minutes INTEGER NOT NULL,
    block_start_at TIMESTAMPTZ NOT NULL,
    block_end_at TIMESTAMPTZ NOT NULL,
    usable_from TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED','CANCELED','REPLACED')),
    origin_kind VARCHAR(20) NOT NULL CHECK (origin_kind IN ('MANUAL','FIXED','CHANGE','EXCHANGE')),
    quota_exempt BOOLEAN NOT NULL DEFAULT FALSE,
    dual_asset_exception BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    canceled_at TIMESTAMPTZ,
    canceled_by_user_id BIGINT REFERENCES users(id),
    cancel_reason VARCHAR(500),
    created_operation_id BIGINT NOT NULL REFERENCES reservation_operations(id),
    canceled_operation_id BIGINT REFERENCES reservation_operations(id),
    UNIQUE (id, reservation_date, time_block_code),
    UNIQUE (id, reservation_date, owner_user_id),
    UNIQUE (id, reservation_date, team_id),
    UNIQUE (id, owner_type),
    FOREIGN KEY (time_block_code, block_start_minute, block_end_minute, duration_minutes)
        REFERENCES time_blocks (code, start_minute, end_minute, duration_minutes),
    FOREIGN KEY (team_id, purpose) REFERENCES teams (id, kind),
    CHECK ((owner_type = 'PERSONAL' AND owner_user_id IS NOT NULL AND team_id IS NULL AND purpose = 'PERSONAL'
            AND owner_user_id = creator_user_id)
        OR (owner_type = 'TEAM' AND owner_user_id IS NULL AND team_id IS NOT NULL AND purpose IN ('REGULAR','ADDITIONAL'))),
    CHECK (block_start_at = ((reservation_date::timestamp + make_interval(mins => block_start_minute)) AT TIME ZONE 'Asia/Seoul')),
    CHECK (block_end_at = ((reservation_date::timestamp + make_interval(mins => block_end_minute)) AT TIME ZONE 'Asia/Seoul')),
    CHECK (usable_from >= block_start_at AND usable_from < block_end_at),
    CHECK (NOT dual_asset_exception OR (owner_type = 'PERSONAL' AND duration_minutes = 90 AND origin_kind IN ('EXCHANGE','CHANGE'))),
    CHECK (NOT quota_exempt OR (owner_type = 'TEAM' AND origin_kind = 'FIXED')),
    CHECK ((status = 'CANCELED') = (canceled_at IS NOT NULL AND canceled_by_user_id IS NOT NULL AND canceled_operation_id IS NOT NULL))
);
CREATE UNIQUE INDEX reservations_personal_active_unique ON reservations (owner_user_id, reservation_date, time_block_code)
    WHERE owner_type = 'PERSONAL' AND status = 'CONFIRMED';
CREATE UNIQUE INDEX reservations_team_active_unique ON reservations (team_id, reservation_date, time_block_code)
    WHERE owner_type = 'TEAM' AND status = 'CONFIRMED';
CREATE INDEX reservations_date_idx ON reservations (reservation_date, time_block_code, id);

CREATE TABLE reservation_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    reservation_date DATE NOT NULL,
    time_block_code VARCHAR(3) NOT NULL,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    claim_kind VARCHAR(20) NOT NULL CHECK (claim_kind IN ('PERSONAL','TEAM')),
    created_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    UNIQUE (reservation_id, asset_id),
    FOREIGN KEY (reservation_id, reservation_date, time_block_code)
        REFERENCES reservations (id, reservation_date, time_block_code),
    FOREIGN KEY (reservation_id, claim_kind) REFERENCES reservations (id, owner_type),
    CHECK (released_at IS NULL OR released_at >= created_at)
);
CREATE UNIQUE INDEX reservation_assets_active_unique ON reservation_assets (reservation_date, time_block_code, asset_id)
    WHERE released_at IS NULL;

CREATE TABLE quota_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    operation_id BIGINT NOT NULL REFERENCES reservation_operations(id),
    quota_date DATE NOT NULL REFERENCES booking_days(reservation_date),
    owner_user_id BIGINT REFERENCES users(id),
    team_id BIGINT REFERENCES teams(id),
    amount_minutes INTEGER NOT NULL,
    entry_kind VARCHAR(20) NOT NULL CHECK (entry_kind IN ('RESERVE','RELEASE')),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (reservation_id, entry_kind),
    FOREIGN KEY (reservation_id, quota_date, owner_user_id)
        REFERENCES reservations (id, reservation_date, owner_user_id),
    FOREIGN KEY (reservation_id, quota_date, team_id)
        REFERENCES reservations (id, reservation_date, team_id),
    CHECK ((owner_user_id IS NOT NULL) <> (team_id IS NOT NULL)),
    CHECK ((entry_kind = 'RESERVE' AND amount_minutes IN (0,60)) OR (entry_kind = 'RELEASE' AND amount_minutes = -60))
);
CREATE INDEX quota_entries_personal_idx ON quota_entries (quota_date, owner_user_id) WHERE owner_user_id IS NOT NULL;
CREATE INDEX quota_entries_team_idx ON quota_entries (quota_date, team_id) WHERE team_id IS NOT NULL;

